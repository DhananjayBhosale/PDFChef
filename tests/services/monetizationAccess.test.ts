import assert from 'node:assert/strict';
import test from 'node:test';
import {
  deliverBlob,
  downloadBlob,
  installOutputAccessHandler,
  installOutputDeliveryHandler,
  type OutputReadyRecord,
} from '../../services/pdfShared.ts';
import { OUTPUT_EVENT } from '../../services/workspace.ts';

test('the first native free job delivers normally and later output is an exact ephemeral preview', async () => {
  const previousWindow = Object.getOwnPropertyDescriptor(globalThis, 'window');
  const events: unknown[] = [];
  Object.defineProperty(globalThis, 'window', {
    configurable: true,
    value: {
      location: { pathname: '/merge' },
      localStorage: { getItem: () => JSON.stringify({ keepLocalHistory: true, autoDownload: true }) },
      dispatchEvent(event: CustomEvent) {
        if (event.type === OUTPUT_EVENT) events.push(event.detail);
        return true;
      },
    },
  });
  const operationIds: string[] = [];
  let jobs = 0;
  let delivered = 0;
  const uninstallAccess = installOutputAccessHandler(async request => {
    operationIds.push(request.operationId);
    jobs += 1;
    return { status: jobs === 1 ? 'deliver' : 'preview' };
  });
  const uninstallDelivery = installOutputDeliveryHandler(async () => { delivered += 1; });
  const firstBlob = new Blob(['first generated result'], { type: 'application/pdf' });
  const previewBlob = new Blob(['second generated result'], { type: 'application/pdf' });
  try {
    assert.deepEqual(await deliverBlob(firstBlob, 'first.pdf', 'application/pdf'), { status: 'delivered' });
    assert.equal(delivered, 1);
    assert.equal((events[0] as OutputReadyRecord).historyRetained, true);

    assert.deepEqual(await deliverBlob(previewBlob, 'second.pdf', 'application/pdf'), { status: 'preview' });
    assert.equal(delivered, 1, 'the preview bypasses native persistence and export');
    const preview = events[1] as OutputReadyRecord;
    assert.equal(preview.blob, previewBlob);
    assert.equal(preview.historyRetained, false);
    assert.equal(preview.accessLocked, true);

    await deliverBlob(previewBlob, 'retry.pdf', 'application/pdf');
    assert.equal(operationIds[1], operationIds[2], 'the same generated bytes retain their metering id');
  } finally {
    uninstallDelivery();
    uninstallAccess();
    if (previousWindow) Object.defineProperty(globalThis, 'window', previousWindow);
    else delete (globalThis as { window?: Window }).window;
  }
});

test('exporting an unchanged source PDF bypasses the job allowance', async () => {
  const previousWindow = Object.getOwnPropertyDescriptor(globalThis, 'window');
  Object.defineProperty(globalThis, 'window', {
    configurable: true,
    value: {
      location: { pathname: '/view' },
      localStorage: { getItem: () => JSON.stringify({ keepLocalHistory: true, autoDownload: true }) },
      dispatchEvent: () => true,
    },
  });
  let accessChecks = 0;
  let deliveries = 0;
  const uninstallAccess = installOutputAccessHandler(async () => {
    accessChecks += 1;
    return { status: 'preview' };
  });
  const uninstallDelivery = installOutputDeliveryHandler(async () => { deliveries += 1; });
  try {
    downloadBlob(new Blob(['unchanged source'], { type: 'application/pdf' }), 'source.pdf', 'application/pdf', { accessScope: 'source' });
    await new Promise(resolve => setTimeout(resolve, 0));
    assert.equal(accessChecks, 0);
    assert.equal(deliveries, 1);
  } finally {
    uninstallDelivery();
    uninstallAccess();
    if (previousWindow) Object.defineProperty(globalThis, 'window', previousWindow);
    else delete (globalThis as { window?: Window }).window;
  }
});
