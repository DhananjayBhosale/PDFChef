import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Writes THIRD_PARTY_NOTICES.md from the two data files the in-app
 * Settings > Open-source licenses page also reads, so the two cannot drift:
 *
 *   services/legal/thirdPartyComponents.json  every shipped component
 *   services/legal/licenseTexts.json          licence texts and NOTICE files
 *
 *   node scripts/generate-third-party-notices.mjs           write the file
 *   node scripts/generate-third-party-notices.mjs --check   fail if it is out of date
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'THIRD_PARTY_NOTICES.md');

const SECTIONS = [
  { kind: 'js', title: 'JavaScript packages' },
  { kind: 'asset', title: 'Bundled assets and embedded libraries' },
  { kind: 'android', title: 'Android libraries' },
  { kind: 'ios', title: 'iOS libraries' },
];

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const fence = (text) => {
  let marks = '```';
  while (text.includes(marks)) marks += '`';
  return `${marks}text\n${text}\n${marks}`;
};

/** The licence ids named by an SPDX-style expression such as "Apache-2.0 AND BSD-3-Clause". */
export const licenseIds = (expression) => expression.split(/\s+(?:AND|OR|WITH)\s+/);

export const renderThirdPartyNotices = (components, { licenses, notices }) => {
  const counts = Object.fromEntries(SECTIONS.map(({ kind }) => [kind, components.filter((item) => item.kind === kind).length]));
  const lines = [
    '# Third-party notices',
    '',
    'PDF Chef includes the third-party components below. Each entry gives the version that ships, the licence, the copyright line and the project page. The full text of every licence follows the tables.',
    '',
    'This file is generated by `node scripts/generate-third-party-notices.mjs` from `services/legal/thirdPartyComponents.json` and `services/legal/licenseTexts.json`. The Settings > Open-source licenses page in the app shows the same data, without the other platform’s native libraries. Edit those two files, not this one.',
    '',
    '## What is listed',
    '',
    `- **JavaScript packages (${counts.js})**: the production dependency tree in \`package.json\` at the versions in \`package-lock.json\`. Development tools, type-only \`@types/*\` packages and the Node.js-only \`@napi-rs/canvas\` binaries are not shipped and are not listed.`,
    `- **Bundled assets and embedded libraries (${counts.asset})**: WebAssembly modules, fonts, character maps and trained data that the app serves, including the libraries compiled into those modules.`,
    `- **Android libraries (${counts.android})**: the resolved runtime dependencies of the release build of \`android/app\`, with the versions Gradle selected.`,
    `- **iOS libraries (${counts.ios})**: the Swift packages of the iOS app, at the versions pinned in \`Package.resolved\`.`,
    '',
    'Where a package offers a choice of licences, the entry names the one the app uses and says so in its note. Google Play services, Play Core and ML Kit are proprietary Google libraries rather than open source; they are listed for completeness and their terms are linked in the licence section.',
  ];

  for (const { kind, title } of SECTIONS) {
    const rows = components.filter((item) => item.kind === kind);
    lines.push('', `## ${title}`, '', '| Component | Version | License | Copyright | Project |', '| --- | --- | --- | --- | --- |');
    for (const item of rows) {
      lines.push(`| ${cell(item.name)} | ${cell(item.version)} | ${cell(item.license)} | ${cell(item.copyright)} | <${item.url}> |`);
    }
    const noted = rows.filter((item) => item.note);
    if (noted.length) {
      lines.push('', 'Notes:', '');
      for (const item of noted) lines.push(`- **${cell(item.name)} ${cell(item.version)}**: ${cell(item.note)}`);
    }
  }

  if (notices.length) {
    lines.push('', '## NOTICE files', '', 'These Apache-2.0 components ship a NOTICE file. Its text is reproduced as the licence requires.');
    for (const notice of notices) lines.push('', `### ${notice.component}`, '', fence(notice.text));
  }

  lines.push('', '## License texts', '', 'Each text is given once. The copyright holders of the components that use it are named in the tables above.');
  for (const id of Object.keys(licenses).sort((a, b) => a.localeCompare(b))) {
    const users = components.filter((item) => licenseIds(item.license).includes(id)).length;
    lines.push('', `### ${licenses[id].name} (${id})`, '', `Used by ${users} ${users === 1 ? 'component' : 'components'}.`, '', fence(licenses[id].text));
  }
  return `${lines.join('\n')}\n`;
};

export const readNoticeData = async () => {
  const read = async (path) => JSON.parse(await readFile(resolve(root, path), 'utf8'));
  return {
    components: await read('services/legal/thirdPartyComponents.json'),
    texts: await read('services/legal/licenseTexts.json'),
  };
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { components, texts } = await readNoticeData();
  const markdown = renderThirdPartyNotices(components, texts);
  if (process.argv.includes('--check')) {
    const current = await readFile(outputPath, 'utf8').catch(() => '');
    if (current !== markdown) {
      console.error('THIRD_PARTY_NOTICES.md is out of date. Run: node scripts/generate-third-party-notices.mjs');
      process.exitCode = 1;
    } else {
      console.log(`THIRD_PARTY_NOTICES.md is up to date (${components.length} components).`);
    }
  } else {
    await writeFile(outputPath, markdown);
    console.log(`Wrote THIRD_PARTY_NOTICES.md (${components.length} components, ${Object.keys(texts.licenses).length} licence texts).`);
  }
}
